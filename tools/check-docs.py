"""Check active documentation paths without reading personal or historical content."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED_REFERENCES = {'distribution/docs/application-contract.md',
                        'distribution/CLAUDE.md', 'distribution/private/profile.md'}


def check(root=ROOT):
    root = Path(root).resolve()
    documents = [*root.glob('*.md'), *root.joinpath('docs').glob('*.md'),
                 *root.joinpath('distribution').glob('*.md'),
                 *root.joinpath('distribution/docs').glob('*.md')]
    checked, links, errors = 0, 0, []
    for document in sorted(documents):
        if 'conflict' in document.name.lower():
            continue
        checked += 1
        text = document.read_text(encoding='utf-8')
        for link in re.findall(r'\[[^\]]*\]\(([^)]+)\)', text):
            if '://' in link or link.startswith(('#', 'mailto:')):
                continue
            target = (document.parent / link.split('#')[0]).resolve()
            try:
                name = target.relative_to(root).as_posix()
            except ValueError:
                errors.append({'document': document.relative_to(root).as_posix(), 'link': link,
                               'reason': 'El enlace sale de esta instalación'})
                continue
            # Dated evidence is preserved, not regenerated by a documentation check.
            if name.startswith(('auditoria/', 'outputs/', 'data/')):
                continue
            if name in GENERATED_REFERENCES or name == 'private/profile.md':
                continue  # Created by the builder, or optional personal context.
            links += 1
            if not target.is_file():
                errors.append({'document': document.relative_to(root).as_posix(), 'link': link,
                               'reason': 'Falta el archivo enlazado'})
    return {'ok': not errors, 'documents': checked, 'links': links, 'errors': errors,
            'limits': ['No valida enlaces web, archivos históricos ni pruebas de aceptación humana.',
                       'Las referencias generadas se comprueban en las pruebas de distribución.']}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    result = check(args.root)
    print(json.dumps(result, ensure_ascii=False, indent=2))
    raise SystemExit(0 if result['ok'] else 1)
